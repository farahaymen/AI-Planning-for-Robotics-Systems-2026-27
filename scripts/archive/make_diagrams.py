def diagram_course_arc():
    """The ten week arc, for the proposal and the design baseline."""
    stages = [
        ("1-3", "ROS 2, robot\nmodel, sensors", PRIMARY),
        ("4-5", "mapping and\nlocalisation", PRIMARY),
        ("P1", "Project 1", GOOD),
        ("6-7", "Nav2 and\nrobust autonomy", PRIMARY),
        ("8-9", "RL environment\nand training", ACCENT),
        ("10", "hybrid and\nsim-to-real", ACCENT),
        ("P2", "Grand\nChallenge", GOOD),
    ]
    fig, ax = plt.subplots(figsize=(10.0, 1.9))
    x = 0.0
    for i, (week, label, colour) in enumerate(stages):
        width = 1.5 if week in ("P1", "P2") else 2.0
        ax.add_patch(plt.Rectangle((x, 0.25), width, 0.9, facecolor=colour,
                                   alpha=0.16, edgecolor=colour, lw=1.6,
                                   joinstyle="round"))
        ax.text(x + width / 2, 0.92, week, ha="center", fontsize=9.5,
                weight="bold", color=colour)
        ax.text(x + width / 2, 0.55, label, ha="center", va="center",
                fontsize=8.5, color=INK)
        if i < len(stages) - 1:
            ax.annotate("", xy=(x + width + 0.28, 0.7), xytext=(x + width + 0.02, 0.7),
                        arrowprops=dict(arrowstyle="-|>", color=MUTED, lw=1.4))
        x += width + 0.3
    ax.text(x / 2, 0.02, "implement the concept, configure the production system, "
                         "measure both", ha="center", fontsize=8.5, color=MUTED,
            style="italic")
    ax.set_xlim(-0.2, x); ax.set_ylim(-0.05, 1.3)
    ax.axis("off")
    save(fig, "diagram_course_arc")


