def render_dot(source: str, name: str, engine: str = "dot") -> None:
    path = OUT / f"{name}.png"
    subprocess.run([engine, "-Tpng", "-Gdpi=200", "-o", str(path)],
                   input=source, text=True, check=True)
    print(f"  docs/figures/{name}.png")


def node_style(fill=PAPER, colour=INK, shape="box"):
    return (f'shape={shape}, style="rounded,filled", fillcolor="{fill}", '
            f'color="{colour}", fontname="{FONT}", fontsize=10, '
            f'penwidth=1.2, margin="0.16,0.09"')


